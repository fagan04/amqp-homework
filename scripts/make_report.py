#!/usr/bin/env python3
"""Generate docs/REPORT.md (resilience & benchmark report) from results/.
Run after scripts/chaos.sh, scripts/bench.sh and scripts/plot_results.py."""
import csv
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = os.path.join(ROOT, "results")


def rows(p):
    with open(os.path.join(R, p)) as f:
        return list(csv.DictReader(f))


def fmt(v, nd=0):
    try:
        x = float(v)
    except (TypeError, ValueError):
        return v or "–"
    return f"{x:,.{nd}f}"


def table(header, body):
    out = "| " + " | ".join(header) + " |\n|" + "---|" * len(header) + "\n"
    for r in body:
        out += "| " + " | ".join(str(c) for c in r) + " |\n"
    return out


chaos = rows("chaos_summary.csv")
tp = rows("bench/throughput.csv")
sz = rows("bench/size.csv")
pf = rows("bench/consumer.csv")
lat = rows("bench/latency.csv")
total = sum(int(r["messages"]) for r in chaos)
passed = sum(1 for r in chaos if r["zero_loss"] == "True")
best = max(tp, key=lambda r: float(r["throughput_msg_s"]))

md = f"""# Resilience & Benchmark Report — INFT 6000 HW2

> Generated by `scripts/make_report.py` from the files in `results/`. The full technical report
> (architecture, design rationale, discussion) is the team's shared document; this file is the
> reproducible data appendix that lives with the code. Environment: see `docs/TEST-HARNESS.md`.

## Headline

* **{passed} / {len(chaos)} failure scenarios with zero message loss** ({total:,} messages in total).
* Peak confirmed publish throughput: **{fmt(best['throughput_msg_s'])} msg/s**
  ({best['workers']} workers, confirm window {best['inflight']}, 512 B persistent, majority-replicated).
* End-to-end latency p99 at 2,000 msg/s: **{fmt(next(r for r in lat if r['offered_rate']=='2000')['e2e_p99_ms'], 1)} ms**.

## Chaos scenarios

Load: 4 producer workers, 2,000 msg/s total, 512 B persistent; 1 consumer, prefetch 100.
"Publish stall" = seconds with confirms below 50% of the offered rate.

"""
md += table(
    ["Scenario", "Messages", "Zero loss", "Dupes removed", "Out of order", "Re-published", "Leader before → after",
     "Election (s)*", "Publish stall (s)", "Consumer detect / reconnect (s)", "Rejoin (s)"],
    [[r["scenario"], fmt(r["messages"]), r["zero_loss"], r["duplicates_removed"], r["out_of_order"], r["republished"],
      f"{r.get('leader_before') or '–'} → {r.get('leader_after') or '–'}", r.get("election_s") or "–",
      r.get("publish_stall_s") or "–",
      f"{r.get('consumer_detect_s') or '–'} / {r.get('consumer_failover_s') or '–'}" if r["scenario"] != "rolling-restart" else f"– / {r.get('consumer_failover_s')}",
      r.get("rejoin_s") or "–"] for r in chaos])
md += """
\\* Election time is when `clustermon` (250 ms polling of the management API) first showed the new leader.
During a silent partition the cluster-wide API view blocks until `net_ticktime` expires, so for
`partition-leader` the client-side measure (publishes resumed after the stall) is the accurate one.

Timelines (grey = a node down or isolated):

"""
for s in ["node-crash", "leader-crash", "partition", "partition-leader", "quorum-loss", "rolling-restart"]:
    md += f"![{s}](charts/chaos-{s}.png)\n\n"

md += "## Benchmarks\n\n### Publish throughput vs. confirm window\n\n![throughput](charts/bench-throughput.png)\n\n"
md += table(["Workers", "Window", "Messages", "Confirmed msg/s", "Confirm p50 (ms)", "Confirm p99 (ms)"],
            [[r["workers"], r["inflight"], fmt(r["msgs"]), fmt(r["throughput_msg_s"]), r["confirm_p50_ms"], r["confirm_p99_ms"]] for r in tp])
md += "\n### Message size (4 workers, window 128)\n\n![size](charts/bench-size.png)\n\n"
md += table(["Size (B)", "msg/s", "MB/s", "Confirm p50 (ms)", "Confirm p99 (ms)"],
            [[r["size"], fmt(r["throughput_msg_s"]), r["throughput_MB_s"], r["confirm_p50_ms"], r["confirm_p99_ms"]] for r in sz])
md += "\n### Consumer prefetch (manual ack)\n\n![prefetch](charts/bench-prefetch.png)\n\n"
md += table(["Prefetch", "Messages", "Elapsed (s)", "Consumed msg/s"],
            [[r["prefetch"], fmt(r["msgs"]), r["elapsed_s"], fmt(r["throughput_msg_s"])] for r in pf])
md += "\n### Latency under load\n\n![latency](charts/bench-latency.png)\n\n"
md += table(["Offered msg/s", "Achieved msg/s", "E2E p50 (ms)", "E2E p95 (ms)", "E2E p99 (ms)", "E2E max (ms)", "Confirm p50 (ms)", "Confirm p99 (ms)"],
            [[fmt(r["offered_rate"]), fmt(r["achieved_msg_s"]), r["e2e_p50_ms"], r["e2e_p95_ms"], r["e2e_p99_ms"], r["e2e_max_ms"], r["confirm_p50_ms"], r["confirm_p99_ms"]] for r in lat])
md += """
Above ~3,000 msg/s the single consumer (sharing 2 vCPUs with 3 brokers and 4 publishers) falls behind,
so end-to-end latency becomes queueing delay; confirm latency stays low, i.e. replication is not the bottleneck.

## Defects found by these tests (all fixed before the final run)

1. Nacked channel kept nacking after a leader election → re-send on a fresh channel.
2. Switch-back requeued prefetched deliveries → graceful cancel + drain before reconnecting.
3. Publisher hung during a silent partition (blocked TCP write) → 5 s write deadline on the socket.
4. `pause_minority` never triggered in a short partition (`net_ticktime` 60 s) → `net_ticktime = 15`.
5. Failover waited 23.6 s on `Close()` to an unresponsive broker → abandon failed sessions asynchronously.
6. Rate limiter starved confirm processing (bogus 1 s confirm latency) → wait on slot *or* confirm.
"""
with open(os.path.join(ROOT, "docs", "REPORT.md"), "w") as f:
    f.write(md)
print("wrote docs/REPORT.md")
